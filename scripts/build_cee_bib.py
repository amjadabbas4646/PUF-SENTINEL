"""Build CEE_SUBMISSION/bibliography.bib for the Elsevier submission.

Sources
    FINAL_MANUSCRIPT_SOURCE/bibliography.bib   entries of the previous version
    build/new_entries_r2.bib                   entries added in the second
                                               revision, generated from Crossref
                                               records by scripts/crossref_to_bib.py
Changes
    * the IEEEtran BSTcontrol entry is dropped (not a reference)
    * the two CHES papers, which Crossref lists only under the series title,
      get their proceedings title, series and volume
    * non-ASCII letters are written as LaTeX accents, so that bibtex sorts and
      prints them under any input encoding
    * one entry that has no Crossref record (an IACR ePrint report) is added;
      its title, authors and number were checked on eprint.iacr.org

Usage:  python scripts/build_cee_bib.py
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "CEE_SUBMISSION" / "bibliography.bib"

ACCENTS = {
    "ë": "{\\\"e}", "š": "{\\v{s}}", "ä": "{\\\"a}", "ö": "{\\\"o}",
    "ü": "{\\\"u}", "é": "{\\'e}", "è": "{\\`e}", "á": "{\\'a}",
    "í": "{\\'i}", "ó": "{\\'o}", "ú": "{\\'u}", "ç": "{\\c{c}}",
    "ğ": "{\\u{g}}", "č": "{\\v{c}}", "ć": "{\\'c}", "ß": "{\\ss}",
}

CHES = {
    "maes2015secure": ("Cryptographic Hardware and Embedded Systems (CHES 2015)", "9293"),
    "delvaux2016efficient": ("Cryptographic Hardware and Embedded Systems (CHES 2016)", "9813"),
}

EPRINT = """@misc{becker2014active,
  author       = {Becker, Georg T. and Kumar, Raghavan},
  title        = {{Active and Passive Side-Channel Attacks on Delay Based PUF Designs}},
  howpublished = {Cryptology ePrint Archive, Paper 2014/287},
  year         = {2014},
  url          = {https://eprint.iacr.org/2014/287}
}
"""


def split_entries(text: str) -> list[str]:
    starts = [m.start() for m in re.finditer(r"^@", text, flags=re.M)]
    return [text[a:b].strip() + "\n" for a, b in zip(starts, starts[1:] + [len(text)])]


def key_of(entry: str) -> str:
    return re.match(r"@\w+\{([^,]+),", entry).group(1).strip()


def fix_ches(entry: str, title: str, volume: str) -> str:
    entry = re.sub(r"^@incollection", "@inproceedings", entry)
    entry = re.sub(r"booktitle\s*=\s*\{Lecture Notes in Computer Science\}",
                   "booktitle = {" + title + "}", entry)
    entry = entry.replace("  pages ", f"  series    = {{Lecture Notes in Computer Science}},\n"
                                      f"  volume    = {{{volume}}},\n  pages ", 1)
    return entry


def main() -> None:
    old = split_entries((ROOT / "FINAL_MANUSCRIPT_SOURCE" / "bibliography.bib").read_text(encoding="utf-8"))
    new = split_entries((ROOT / "build" / "new_entries_r2.bib").read_text(encoding="utf-8"))
    out, seen = [], set()
    for e in old + new:
        if e.startswith("@IEEEtranBSTCTL"):
            continue
        k = key_of(e)
        if k in seen:
            raise SystemExit(f"duplicate key {k}")
        seen.add(k)
        if k in CHES:
            e = fix_ches(e, *CHES[k])
        if k == "wisiol2020splitting":
            # TCHES numbers its issues by year; the DOI gives issue 3 of 2020
            e = e.replace("  pages ", "  volume    = {2020},\n  number    = {3},\n  pages ", 1)
        out.append(e)
    out.append(EPRINT)
    text = "\n".join(out)
    for ch, rep in ACCENTS.items():
        text = text.replace(ch, rep)
    bad = sorted({c for c in text if ord(c) > 127})
    if bad:
        raise SystemExit("non-ASCII characters left: " + " ".join(f"U+{ord(c):04X}" for c in bad))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("% Generated by scripts/build_cee_bib.py. Do not edit.\n\n" + text, encoding="ascii")
    print(f"{len(out)} entries written to {OUT}")


if __name__ == "__main__":
    main()
